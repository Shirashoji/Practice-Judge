function isValidSkill (skillId) {
    return Object.prototype.hasOwnProperty.call(SKILLS, skillId);
}

// 提出のステータスから適切なSkillを選ぶ
function skillForSubmission (status) {
    if (status === 'AC') {
        return 'post_ac_review';
    }
    return 'wa_diagnosis';
}

// returns: { system, tools }
// system は「共通ルール + Skill固有 + 現在の状況」の順に連結する。
function getSkill (skillId, situation) {
    const skill = SKILLS[skillId];
    if (skill == null) {
        throw new Error(`未知のskill_id: ${skillId}`);
    }

    const system = [
        guard.COMMON_RULES,
        skill.instructions,
        guard.situationBlock(situation),
    ].join('\n\n---\n\n');

    return { system, tools: tools.toolsForSkill(skillId) };
}

function listSkills () {
    return Object.entries(SKILLS).map(([id, s]) => ({ id, label: s.label }));
}

module.exports = { SKILLS, isValidSkill, skillForSubmission, getSkill, listSkills };
